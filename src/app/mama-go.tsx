import React, { useEffect, useMemo, useRef, useState } from "react";
import {
  ActivityIndicator,
  Alert,
  KeyboardAvoidingView,
  Platform,
  Pressable,
  SafeAreaView,
  ScrollView,
  StyleSheet,
  Text,
  TextInput,
  View,
} from "react-native";
import { Ionicons } from "@expo/vector-icons";
import AsyncStorage from "@react-native-async-storage/async-storage";
import { useLocalSearchParams, useRouter } from "expo-router";
import {
  ExpoSpeechRecognitionModule,
  useSpeechRecognitionEvent,
} from "expo-speech-recognition";
import { auth, db } from "../services/firebase";
import {
  doc,
  getDoc,
  setDoc,
  serverTimestamp,
} from "firebase/firestore";

type ChecklistItem = {
  id: string;
  label: string;
  essential?: boolean;
};
type ChecklistSection = {
  title: string;
  items: ChecklistItem[];
};
type MamaGoResponse = {
  title: string;
  summary?: string;
  duration?: string;
  sections: ChecklistSection[];
};

// Android emulator: 10.0.2.2. For a physical phone, replace with your laptop's
// Wi-Fi IPv4 address, for example http://192.168.1.5:3000.
const API_BASE_URL = "http://localhost:3000";
const STORAGE_KEY = "mamamind_mama_go_checklist";

const C = {
  yellow: "#FFDA57",
  teal: "#19B7B0",
  deepTeal: "#0E7C86",
  white: "#FFFFFF",
  coral: "#FF6B6B",
  cream: "#FFF9E8",
  paleTeal: "#E8F8F6",
  dark: "#164F52",
  muted: "#648384",
  line: "#DDEDEA",
};

export default function MamaGoScreen() {
  const router = useRouter();
  const params = useLocalSearchParams<{
    request?: string | string[];
    autoGenerate?: string | string[];
  }>();
  const [request, setRequest] = useState("");
  const [checklist, setChecklist] = useState<MamaGoResponse | null>(null);
  const [checkedIds, setCheckedIds] = useState<string[]>([]);
  const [loading, setLoading] = useState(false);
  const [listening, setListening] = useState(false);
  const [voiceError, setVoiceError] = useState("");
  const [restoring, setRestoring] = useState(true);
  const autoGeneratedRequestRef = useRef("");
  const saveChecklistToFirestore = async (
  checklistData: any[],
  checkedItemIds: string[],
  outingRequest: string
) => {
  const user = auth.currentUser;

  if (!user) {
    console.log("Please log in to sync your checklist.");
    return;
  }

  try {
    await setDoc(
      doc(db, "users", user.uid, "mamaGoChecklists", "latest"),
      {
        checklist: checklistData,
        checkedIds: checkedItemIds,
        request: outingRequest,
        updatedAt: serverTimestamp(),
      },
      { merge: true }
    );

    console.log("Mama Go checklist synced to Firestore!");
  } catch (error) {
    console.error("Firestore checklist save failed:", error);
  }
};
const loadChecklistFromFirestore = async () => {
  const user = auth.currentUser;

  if (!user) return;

  try {
    const checklistRef = doc(
      db,
      "users",
      user.uid,
      "mamaGoChecklists",
      "latest"
    );

    const snapshot = await getDoc(checklistRef);

    if (snapshot.exists()) {
      const data = snapshot.data();

      setChecklist(data.checklist ?? []);
      setCheckedIds(data.checkedIds ?? []);

      // Restore the request too if your screen has request state.
      // Example: setRequest(data.request ?? "");
    }
  } catch (error) {
    console.error("Firestore checklist load failed:", error);
  }
};

  // Restore the latest checklist and ticked items whenever this screen opens.
  useEffect(() => {
    let cancelled = false;

    async function restoreChecklist() {
      try {
        const saved = await AsyncStorage.getItem(STORAGE_KEY);
        if (saved && !cancelled) {
          const parsed = JSON.parse(saved);
          if (parsed?.checklist && Array.isArray(parsed.checkedIds)) {
            setChecklist(parsed.checklist);
            setCheckedIds(parsed.checkedIds);
          }
        }
      } catch (error) {
        console.warn("Could not restore MamaGo checklist:", error);
      } finally {
        if (!cancelled) setRestoring(false);
      }
    }

    restoreChecklist();
    return () => {
      cancelled = true;
    };
  }, []);

  // Persist checklist content and checkbox selections on this device.
  useEffect(() => {
    if (restoring || !checklist) return;
    AsyncStorage.setItem(
      STORAGE_KEY,
      JSON.stringify({ checklist, checkedIds })
    ).catch((error) => console.warn("Could not save MamaGo checklist:", error));
  }, [checklist, checkedIds, restoring]);

  // A specific voice request arrives from Mother Dashboard. Generate once,
  // after storage restoration, and use the parameter directly to avoid stale state.
  useEffect(() => {
    const rawRequest = params.request;
    const incomingRequest = (Array.isArray(rawRequest) ? rawRequest[0] : rawRequest)?.trim();
    const rawAutoGenerate = params.autoGenerate;
    const shouldAutoGenerate = (Array.isArray(rawAutoGenerate) ? rawAutoGenerate[0] : rawAutoGenerate) === "true";

    if (restoring || !shouldAutoGenerate || !incomingRequest) return;
    if (autoGeneratedRequestRef.current === incomingRequest) return;

    autoGeneratedRequestRef.current = incomingRequest;
    setRequest(incomingRequest);
    void generateChecklist(incomingRequest);
  // Intentionally keyed to route params and restoration state to avoid rerunning
  // when checklist state changes during generation.
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [params.request, params.autoGenerate, restoring]);

  useSpeechRecognitionEvent("result", (event) => {
    const transcript = event.results?.[0]?.transcript;
    if (transcript) setRequest((previous) => `${previous} ${transcript}`.trim());
    setListening(false);
  });
  useSpeechRecognitionEvent("end", () => setListening(false));
  useSpeechRecognitionEvent("error", (event) => {
    setListening(false);
    setVoiceError(event.message || "Voice input could not start. You can type your request instead.");
  });

  const allItems = useMemo(
    () => checklist?.sections.flatMap((section) => section.items) ?? [],
    [checklist]
  );
  const completedCount = allItems.filter((item) => checkedIds.includes(item.id)).length;
  const progress = allItems.length ? completedCount / allItems.length : 0;

  async function startVoiceInput() {
    setVoiceError("");
    try {
      const permission = await ExpoSpeechRecognitionModule.requestPermissionsAsync();
      if (!permission.granted) {
        setVoiceError("Microphone permission is needed for voice input. You can type your request instead.");
        return;
      }
      setListening(true);
      ExpoSpeechRecognitionModule.start({ lang: "en-IN", interimResults: false });
    } catch (error) {
      setListening(false);
      setVoiceError("Voice input is unavailable on this build. Type your outing request below.");
    }
  }

  async function generateChecklist(requestOverride?: string) {
    const requestToUse = (requestOverride ?? request).trim();
    if (!requestToUse) {
      Alert.alert("Tell MamaGo about your outing", "For example: I'm taking my baby to the hospital for a checkup.");
      return;
    }
    setLoading(true);
    setVoiceError("");
    try {
      const response = await fetch(`${API_BASE_URL}/api/mama-go`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ request: requestToUse }),
      });
      const data = await response.json();
      if (!response.ok) throw new Error(data.error || "MamaGo couldn't prepare your list.");
      if (!data.title || !Array.isArray(data.sections)) {
        throw new Error("The server returned an unexpected checklist format.");
      }
      // Ensure the Mom and Baby sections are always represented, even if the AI
      // occasionally returns a different section title or omits one.
      const sections: ChecklistSection[] = [...data.sections];
      const hasMom = sections.some((s) => /mom|mother|mum|mama/i.test(s.title));
      const hasBaby = sections.some((s) => /baby|infant|child/i.test(s.title));
      if (!hasMom) sections.unshift({ title: "Mom essentials", items: [] });
      if (!hasBaby) {
        const momIndex = sections.findIndex((s) => /mom|mother|mum|mama/i.test(s.title));
        sections.splice(momIndex >= 0 ? momIndex + 1 : 0, 0, { title: "Baby essentials", items: [] });
      }
      setChecklist({ ...data, sections });
      setCheckedIds([]);
    } catch (error) {
      const message = error instanceof Error ? error.message : "Check that your backend is running and the API address is correct.";
      Alert.alert("Couldn't generate the checklist", `${message}\n\nCheck that your server is running on port 3000 and that API_BASE_URL matches your device.`);
    } finally {
      setLoading(false);
    }
  }

  function toggleItem(id: string) {
    setCheckedIds((current) => {
      const next = current.includes(id)
        ? current.filter((itemId) => itemId !== id)
        : [...current, id];
      if (checklist && !restoring) {
        AsyncStorage.setItem(
          STORAGE_KEY,
          JSON.stringify({ checklist, checkedIds: next })
        ).catch((error) => console.warn("Could not save MamaGo checkbox:", error));
      }
      return next;
    });
  }

  function resetCheckboxes() {
    setCheckedIds([]);
    if (checklist && !restoring) {
      AsyncStorage.setItem(
        STORAGE_KEY,
        JSON.stringify({ checklist, checkedIds: [] })
      ).catch((error) => console.warn("Could not reset MamaGo checkboxes:", error));
    }
  }

  return (
    <SafeAreaView style={styles.safe}>
      <KeyboardAvoidingView style={styles.flex} behavior={Platform.OS === "ios" ? "padding" : undefined}>
        <View style={styles.header}>
          <Pressable accessibilityRole="button" onPress={() => router.back()} style={styles.backButton}>
            <Ionicons name="arrow-back" size={22} color={C.dark} />
          </Pressable>
          <View style={styles.headerText}>
            <Text style={styles.eyebrow}>MAMAMIND · MAMAGO</Text>
            <Text style={styles.headerTitle}>Outing checklist</Text>
          </View>
          <View style={styles.headerIcon}><Ionicons name="bag-handle-outline" size={23} color={C.dark} /></View>
        </View>

        <ScrollView contentContainerStyle={styles.content} keyboardShouldPersistTaps="handled">
          {restoring && (
            <View style={styles.restoreNotice}>
              <ActivityIndicator color={C.deepTeal} />
              <Text style={styles.restoreText}>Restoring your last checklist…</Text>
            </View>
          )}
          <View style={styles.hero}>
            <View style={styles.heroIcon}><Ionicons name="heart" size={25} color={C.dark} /></View>
            <Text style={styles.heroTitle}>One less thing to remember.</Text>
            <Text style={styles.heroText}>Tell MamaGo where you're going. It will prepare a personalised checklist for both you and your baby.</Text>
          </View>

          <View style={styles.inputCard}>
            <Text style={styles.label}>Where are you going?</Text>
            <TextInput
              value={request}
              onChangeText={setRequest}
              placeholder="E.g. Hospital visit with my 6-month-old baby..."
              placeholderTextColor="#91A9A8"
              multiline
              style={styles.input}
              textAlignVertical="top"
            />
            <Pressable onPress={startVoiceInput} style={[styles.voiceButton, listening && styles.voiceButtonActive]}>
              <Ionicons name={listening ? "ear" : "mic-outline"} size={19} color={C.deepTeal} />
              <Text style={styles.voiceButtonText}>{listening ? "Listening… speak now" : "Speak your request"}</Text>
            </Pressable>
            {!!voiceError && <Text style={styles.errorText}>{voiceError}</Text>}
            <Pressable onPress={()=>generateChecklist()} disabled={loading} style={[styles.generateButton, loading && styles.disabledButton]}>
              {loading ? <ActivityIndicator color={C.dark} /> : <><Text style={styles.generateText}>Create my checklist</Text><Ionicons name="arrow-forward" size={18} color={C.dark} /></>}
            </Pressable>
          </View>

          {checklist && (
            <View style={styles.checklistWrap}>
              <View style={styles.listHeading}>
                <View style={{ flex: 1 }}>
                  <Text style={styles.listTitle}>{checklist.title}</Text>
                  {!!checklist.summary && <Text style={styles.listSummary}>{checklist.summary}</Text>}
                  {!!checklist.duration && <Text style={styles.duration}><Ionicons name="time-outline" size={14} color={C.muted} />  {checklist.duration}</Text>}
                </View>
                <View style={styles.countCircle}><Text style={styles.countNumber}>{completedCount}/{allItems.length}</Text><Text style={styles.countCaption}>packed</Text></View>
              </View>
              <View style={styles.progressTrack}><View style={[styles.progressFill, { width: `${progress * 100}%` }]} /></View>

              {checklist.sections.map((section, sectionIndex) => {
                const isMom = /mom|mother|mum|mama/i.test(section.title);
                const isBaby = /baby|infant|child/i.test(section.title);
                const sectionColor = isMom ? C.cream : isBaby ? C.paleTeal : "#FFFFFF";
                const sectionIcon = isMom ? "heart-outline" : isBaby ? "happy-outline" : "bag-outline";
                return (
                  <View key={`${section.title}-${sectionIndex}`} style={[styles.sectionCard, { backgroundColor: sectionColor }]}>
                    <View style={styles.sectionHeading}>
                      <View style={styles.sectionIcon}><Ionicons name={sectionIcon as any} size={19} color={C.deepTeal} /></View>
                      <Text style={styles.sectionTitle}>{section.title}</Text>
                    </View>
                    {section.items.map((item) => {
                      const isChecked = checkedIds.includes(item.id);
                      return (
                        <Pressable key={item.id} accessibilityRole="checkbox" accessibilityState={{ checked: isChecked }} onPress={() => toggleItem(item.id)} style={styles.itemRow}>
                          <View style={[styles.checkbox, isChecked && styles.checkboxChecked]}>
                            {isChecked && <Ionicons name="checkmark" size={15} color={C.white} />}
                          </View>
                          <View style={styles.itemTextWrap}>
                            <Text style={[styles.itemLabel, isChecked && styles.itemLabelChecked]}>{item.label}</Text>
                            {item.essential === true && <Text style={styles.essential}>ESSENTIAL</Text>}
                          </View>
                        </Pressable>
                      );
                    })}
                    {section.items.length === 0 && <Text style={styles.emptySection}>No items returned for this section. Try generating the list again.</Text>}
                  </View>
                );
              })}
              <Pressable onPress={resetCheckboxes} style={styles.resetButton}>
                <Ionicons name="refresh-outline" size={17} color={C.deepTeal} />
                <Text style={styles.resetText}>Untick all items</Text>
              </Pressable>
              {allItems.length > 0 && completedCount === allItems.length && (
                <View style={styles.doneBanner}><Ionicons name="checkmark-circle" size={20} color={C.deepTeal} /><Text style={styles.doneText}>All packed. You're ready to go!</Text></View>
              )}
            </View>
          )}
          <Text style={styles.footerNote}>MamaGo helps you prepare. Adjust the list to suit your family's needs.</Text>
        </ScrollView>
      </KeyboardAvoidingView>
    </SafeAreaView>
  );
}

